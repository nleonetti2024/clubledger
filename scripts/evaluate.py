"""Run every sample receipt through the full pipeline and compare with expected results.

Usage:
    python scripts/evaluate.py                 # offline reader (default, free)
    CLUBLEDGER_EXTRACTOR=anthropic ANTHROPIC_API_KEY=... python scripts/evaluate.py
    python scripts/evaluate.py --markdown docs/evaluation-results.md

Uses a throw-away in-memory database, so it never touches your real data.
Exit code is 1 if any expected flag is missed (useful in CI).
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from clubledger import db  # noqa: E402
from clubledger.config import Config, load_dotenv  # noqa: E402
from clubledger.extraction import build_extractor  # noqa: E402
from clubledger.policy import load_policy  # noqa: E402
from clubledger.workflow import PENDING, submit_expense  # noqa: E402

SAMPLES = ROOT / "data" / "sample_receipts"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--markdown", help="also write a Markdown report to this path")
    args = parser.parse_args()

    load_dotenv()
    config = Config()
    policy = load_policy(config.POLICY_PATH)
    primary, fallback = build_extractor(config, policy.category_keywords)
    manifest = json.loads((SAMPLES / "expected.json").read_text())
    as_of = date.fromisoformat(manifest["as_of"])

    conn = db.connect(":memory:")
    db.init_schema(conn)

    rows = []
    field_hits = field_total = 0
    tp = fp = fn = 0
    all_pending = True
    for case in manifest["cases"]:
        exp = case["expected"]
        text = (SAMPLES / case["file"]).read_text()
        res = submit_expense(
            conn, member=case["member"], purpose=case["purpose"],
            claimed_amount=case["claimed_amount"], receipt_text=text,
            extractor=primary, fallback=fallback, policy=policy, as_of=as_of,
        )
        stored = db.get_expense(conn, res.expense_id)
        all_pending &= stored["status"] == PENDING
        x = stored["extraction"]

        checks = {}
        for key in ("vendor", "date", "total", "category"):
            got, want = x.get(key), exp[key]
            if key == "vendor" and got and want:
                ok = got.strip().lower() == want.strip().lower()
            elif key == "total" and got is not None and want is not None:
                ok = abs(got - want) < 0.01
            else:
                ok = got == want
            checks[key] = ok
            field_hits += ok
            field_total += 1

        got_flags = {f["rule_id"] for f in stored["flags"]}
        want_flags = set(exp["flags"])
        tp += len(got_flags & want_flags)
        fp += len(got_flags - want_flags)
        fn += len(want_flags - got_flags)
        rows.append({
            "file": case["file"],
            "fields_ok": all(checks.values()),
            "wrong_fields": [k for k, v in checks.items() if not v],
            "expected_flags": sorted(want_flags),
            "got_flags": sorted(got_flags),
            "flags_ok": got_flags == want_flags,
            "redactions": stored["redactions"],
            "status": stored["status"],
        })

    precision = tp / (tp + fp) if tp + fp else 1.0
    recall = tp / (tp + fn) if tp + fn else 1.0
    summary = {
        "extractor": primary.name,
        "cases": len(rows),
        "field_accuracy": round(field_hits / field_total, 3),
        "flag_precision": round(precision, 3),
        "flag_recall": round(recall, 3),
        "cases_with_exact_flags": sum(r["flags_ok"] for r in rows),
        "all_left_pending_for_human": all_pending,
    }

    print(f"Extractor: {primary.name}   as_of: {as_of}")
    print(f"{'file':<30} {'fields':<8} {'expected':<12} {'got':<12} result")
    for r in rows:
        mark = "PASS" if r["fields_ok"] and r["flags_ok"] else "CHECK"
        print(f"{r['file']:<30} {'ok' if r['fields_ok'] else ','.join(r['wrong_fields']):<8} "
              f"{','.join(r['expected_flags']) or '-':<12} {','.join(r['got_flags']) or '-':<12} {mark}")
    print(json.dumps(summary, indent=2))

    if args.markdown:
        lines = [
            "# Evaluation results",
            "",
            f"Generated by `python scripts/evaluate.py --markdown {args.markdown}`.",
            "",
            f"- Extractor: `{summary['extractor']}`",
            f"- Reference date (as_of): {as_of}",
            f"- Cases: {summary['cases']}",
            f"- Field accuracy (vendor, date, total, category): {summary['field_accuracy']:.1%}",
            f"- Flag precision: {summary['flag_precision']:.1%} · Flag recall: {summary['flag_recall']:.1%}",
            f"- Cases with exactly the expected flags: {summary['cases_with_exact_flags']}/{summary['cases']}",
            f"- Every expense left in `pending_review` for a human: {'yes' if all_pending else 'NO'}",
            "",
            "| Sample | Fields | Expected flags | Got flags | Redactions | Result |",
            "|---|---|---|---|---|---|",
        ]
        for r in rows:
            lines.append(
                f"| `{r['file']}` | {'ok' if r['fields_ok'] else 'wrong: ' + ', '.join(r['wrong_fields'])} "
                f"| {', '.join(r['expected_flags']) or '—'} | {', '.join(r['got_flags']) or '—'} "
                f"| {', '.join(r['redactions']) or '—'} | {'PASS' if r['fields_ok'] and r['flags_ok'] else 'CHECK'} |"
            )
        Path(args.markdown).write_text("\n".join(lines) + "\n")
        print(f"Wrote {args.markdown}")

    return 0 if fn == 0 and all_pending else 1


if __name__ == "__main__":
    raise SystemExit(main())
